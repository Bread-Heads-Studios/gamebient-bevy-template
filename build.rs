use std::process::Command;

fn main() {
    let sha = Command::new("git")
        .args(["rev-parse", "--short=7", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .or_else(|| {
            std::env::var("VERCEL_GIT_COMMIT_SHA")
                .ok()
                .map(|s| s.chars().take(7).collect())
                .filter(|s: &String| !s.is_empty())
        })
        .unwrap_or_else(|| "unknown".into());
    println!(
        "cargo:rustc-env=GX_BUILD_ID={}+{sha}",
        std::env::var("CARGO_PKG_VERSION").unwrap()
    );
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-changed=.git/refs");
    println!("cargo:rerun-if-env-changed=VERCEL_GIT_COMMIT_SHA");
    embed_looks();
}

/// Writes `$OUT_DIR/looks_embedded.rs`: every `assets/looks/<id>/` folder
/// as `(id, [(file, bytes)])`, sorted, so built-in packs work offline on
/// cabinets and on web without a fetch. README.md and dotfiles are skipped.
fn embed_looks() {
    use std::fmt::Write as _;
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("looks_embedded.rs");
    let root = std::path::Path::new("assets/looks");
    println!("cargo:rerun-if-changed=assets/looks");
    let mut code = String::from(
        "/// Generated by build.rs from assets/looks/.\npub static EMBEDDED: &[(&str, &[(&str, &[u8])])] = &[\n",
    );
    // `symlink_metadata`, not `is_dir()` / `is_file()`: those follow links,
    // and runtime packs (`look::pack::read_dir`) refuse links, so a linked
    // folder or file is skipped here too rather than embedded.
    let mut dirs: Vec<_> = std::fs::read_dir(root)
        .map(|rd| {
            rd.filter_map(Result::ok)
                .filter(|e| match plain_kind(&e.path()) {
                    Kind::Dir => true,
                    Kind::Link => {
                        println!(
                            "cargo:warning=assets/looks: skipping symlink {}",
                            e.path().display()
                        );
                        false
                    }
                    _ => false,
                })
                .collect()
        })
        .unwrap_or_default();
    dirs.sort_by_key(|e| e.file_name());
    for dir in dirs {
        let id = dir.file_name().to_string_lossy().to_string();
        println!("cargo:rerun-if-changed={}", dir.path().display());
        writeln!(code, "    ({id:?}, &[").unwrap();
        let mut files: Vec<_> = std::fs::read_dir(dir.path())
            .unwrap()
            .filter_map(Result::ok)
            .filter(|e| match plain_kind(&e.path()) {
                Kind::File => true,
                Kind::Link => {
                    println!(
                        "cargo:warning=assets/looks: skipping symlink {}",
                        e.path().display()
                    );
                    false
                }
                _ => false,
            })
            .collect();
        files.sort_by_key(|e| e.file_name());
        for f in files {
            let name = f.file_name().to_string_lossy().to_string();
            if name.starts_with('.') || name == "README.md" {
                continue;
            }
            let abs = std::fs::canonicalize(f.path()).unwrap();
            println!("cargo:rerun-if-changed={}", abs.display());
            writeln!(
                code,
                "        ({name:?}, include_bytes!({:?})),",
                abs.display().to_string()
            )
            .unwrap();
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    std::fs::write(out, code).unwrap();
}

enum Kind {
    File,
    Dir,
    Link,
    Other,
}

/// What `path` itself is, without following a symlink.
fn plain_kind(path: &std::path::Path) -> Kind {
    match std::fs::symlink_metadata(path) {
        Ok(m) if m.file_type().is_symlink() => Kind::Link,
        Ok(m) if m.is_dir() => Kind::Dir,
        Ok(m) if m.is_file() => Kind::File,
        _ => Kind::Other,
    }
}
