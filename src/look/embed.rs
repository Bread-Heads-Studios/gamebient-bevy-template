//! The build-time generator for built-in Look Packs. Not a module of the
//! crate (`look/mod.rs` does not declare it): `build.rs` includes it with
//!
//! ```ignore
//! #[path = "src/look/embed.rs"]
//! mod look_embed;
//! // in main():
//! look_embed::embed_looks();
//! ```
//!
//! so a game that copies `src/look/` verbatim gets the generator with it.
//! It uses `std` and `blake3` only (`blake3` in `[build-dependencies]`),
//! and shares the content hash, the web split and the naming rules with the
//! crate through the sibling files below.

#[path = "hash.rs"]
mod look_hash;
#[path = "names.rs"]
#[allow(dead_code)] // MANIFEST_FILE etc. are for the crate's validator
mod look_names;
#[path = "split.rs"]
#[allow(dead_code)] // `web_embeds` is for the crate; the generator honours the override
mod look_split;

use std::fmt::Write as _;
use std::path::Path;

/// Test-only override of `look_split::WEB_EMBED_MAX_BYTES` (bytes), so a
/// web build can be made to fetch the template's small sample packs:
/// `GX_WEB_EMBED_MAX=100 ./build.sh web`. Never set it for a shipping build.
const EMBED_MAX_ENV: &str = "GX_WEB_EMBED_MAX";

/// Writes `$OUT_DIR/looks_embedded.rs`: every `assets/looks/<id>/` folder
/// as `(id, [(file, bytes)])`, sorted, so built-in packs work offline on
/// cabinets and on web without a fetch. README.md and dotfiles are skipped.
///
/// On wasm, a pack larger than `look_split::WEB_EMBED_MAX_BYTES` is not
/// embedded: it goes into `FETCHABLE` as `(id, [file], content_hash)` and
/// the game fetches it from `assets/looks/<id>/` when `?look=` names it
/// (`build_web.sh` ships `assets/` beside the bundle). Natively every pack
/// is embedded and `FETCHABLE` is empty.
///
/// Panics (fails the build) on a pack id or file name the validator would
/// refuse: those names become `include_bytes!` paths and fetch URLs.
pub fn embed_looks() {
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("looks_embedded.rs");
    let root = Path::new("assets/looks");
    println!("cargo:rerun-if-changed=assets/looks");
    println!("cargo:rerun-if-env-changed={EMBED_MAX_ENV}");
    let web = std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("wasm32");
    let embed_max = web_embed_max();
    let mut code = String::from(
        "/// Generated by src/look/embed.rs from assets/looks/.\npub static EMBEDDED: &[(&str, &[(&str, &[u8])])] = &[\n",
    );
    let mut fetchable = String::from(
        "/// Generated by src/look/embed.rs: built-in packs left out of this web build.\npub static FETCHABLE: &[(&str, &[&str], &str)] = &[\n",
    );
    // `symlink_metadata`, not `is_dir()` / `is_file()`: those follow links,
    // and runtime packs (`look::pack::read_dir`) refuse links, so a linked
    // folder or file is skipped here too rather than embedded.
    let mut dirs: Vec<_> = std::fs::read_dir(root)
        .map(|rd| {
            rd.filter_map(Result::ok)
                .filter(|e| match plain_kind(&e.path()) {
                    Kind::Dir => true,
                    Kind::Link => {
                        println!(
                            "cargo:warning=assets/looks: skipping symlink {}",
                            e.path().display()
                        );
                        false
                    }
                    _ => false,
                })
                .collect()
        })
        .unwrap_or_default();
    dirs.sort_by_key(|e| e.file_name());
    for dir in dirs {
        let id = dir.file_name().to_string_lossy().to_string();
        check_id(&id);
        println!("cargo:rerun-if-changed={}", dir.path().display());
        let mut files: Vec<_> = std::fs::read_dir(dir.path())
            .unwrap()
            .filter_map(Result::ok)
            .filter(|e| match plain_kind(&e.path()) {
                Kind::File => true,
                Kind::Link => {
                    println!(
                        "cargo:warning=assets/looks: skipping symlink {}",
                        e.path().display()
                    );
                    false
                }
                _ => false,
            })
            .filter(|e| {
                let name = e.file_name().to_string_lossy().to_string();
                !(name.starts_with('.') || name == "README.md")
            })
            .collect();
        files.sort_by_key(|e| e.file_name());
        let mut pack = Vec::new();
        for f in files {
            let name = f.file_name().to_string_lossy().to_string();
            check_file_name(&id, &name);
            let abs = std::fs::canonicalize(f.path()).unwrap();
            println!("cargo:rerun-if-changed={}", abs.display());
            pack.push((name, abs));
        }
        let total: u64 = pack
            .iter()
            .map(|(_, abs)| std::fs::metadata(abs).unwrap().len())
            .sum();
        if web && !look_split::web_embeds_within(total, embed_max) {
            let bytes: std::collections::BTreeMap<String, Vec<u8>> = pack
                .iter()
                .map(|(name, abs)| (name.clone(), std::fs::read(abs).unwrap()))
                .collect();
            let names: Vec<&str> = pack.iter().map(|(n, _)| n.as_str()).collect();
            writeln!(
                fetchable,
                "    ({id:?}, &{names:?}, {:?}),",
                look_hash::content_hash(&bytes)
            )
            .unwrap();
            continue;
        }
        writeln!(code, "    ({id:?}, &[").unwrap();
        // Paths are relative to CARGO_MANIFEST_DIR, never absolute (as in
        // build.rs's content embed): a copy of the game (the editor's gate
        // export) builds into the same target dir, and an absolute path
        // would let this crate embed the copy's files.
        for (name, _) in &pack {
            writeln!(
                code,
                "        ({name:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {:?}))),",
                format!("/assets/looks/{id}/{name}")
            )
            .unwrap();
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    fetchable.push_str("];\n");
    code.push_str(&fetchable);
    std::fs::write(out, code).unwrap();
}

/// `look_split::WEB_EMBED_MAX_BYTES`, unless `GX_WEB_EMBED_MAX` (testing
/// only) says otherwise. A value that is not a byte count fails the build.
fn web_embed_max() -> u64 {
    match std::env::var(EMBED_MAX_ENV) {
        Ok(v) => {
            let max = v.trim().parse().unwrap_or_else(|_| {
                panic!("{EMBED_MAX_ENV}={v:?}: expected a size in bytes, e.g. 100")
            });
            println!(
                "cargo:warning={EMBED_MAX_ENV}={max}: web build embeds Look Packs up to {max} bytes (testing only)"
            );
            max
        }
        Err(_) => look_split::WEB_EMBED_MAX_BYTES,
    }
}

fn check_id(id: &str) {
    if !look_names::is_id(id) {
        panic!(
            "assets/looks/{id}/: a built-in pack's folder name is its id and must be [a-z0-9-]{{1,{}}}",
            look_names::ID_MAX
        );
    }
}

fn check_file_name(id: &str, name: &str) {
    if name != look_names::MANIFEST_FILE && !look_names::is_file_name(name) {
        panic!(
            "assets/looks/{id}/{name}: pack files are {} or [a-z0-9_-]{{1,{}}} ending .png or .ogg",
            look_names::MANIFEST_FILE,
            look_names::FILE_STEM_MAX
        );
    }
}

enum Kind {
    File,
    Dir,
    Link,
    Other,
}

/// What `path` itself is, without following a symlink.
fn plain_kind(path: &Path) -> Kind {
    match std::fs::symlink_metadata(path) {
        Ok(m) if m.file_type().is_symlink() => Kind::Link,
        Ok(m) if m.is_dir() => Kind::Dir,
        Ok(m) if m.is_file() => Kind::File,
        _ => Kind::Other,
    }
}
